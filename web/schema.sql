-- The same tables as Database.createDB in Physics.py, plus GameState for the live 8-ball game.

CREATE TABLE IF NOT EXISTS Ball (
    BALLID INTEGER PRIMARY KEY AUTOINCREMENT,
    BALLNO INTEGER NOT NULL,
    XPOS FLOAT NOT NULL,
    YPOS FLOAT NOT NULL,
    XVEL FLOAT,
    YVEL FLOAT
);

CREATE TABLE IF NOT EXISTS TTable (
    TABLEID INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,
    TIME FLOAT NOT NULL
);

CREATE TABLE IF NOT EXISTS BallTable (
    BALLID INTEGER NOT NULL,
    TABLEID INTEGER NOT NULL,
    FOREIGN KEY (BALLID) REFERENCES Ball (BALLID),
    FOREIGN KEY (TABLEID) REFERENCES TTable (TABLEID)
);

CREATE TABLE IF NOT EXISTS Game (
    GAMEID INTEGER PRIMARY KEY AUTOINCREMENT,
    GAMENAME VARCHAR(64) NOT NULL
);

CREATE TABLE IF NOT EXISTS Player (
    PLAYERID INTEGER PRIMARY KEY AUTOINCREMENT,
    GAMEID INTEGER NOT NULL,
    PLAYERNAME VARCHAR(64) NOT NULL,
    FOREIGN KEY (GAMEID) REFERENCES Game (GAMEID)
);

CREATE TABLE IF NOT EXISTS Shot (
    SHOTID INTEGER PRIMARY KEY AUTOINCREMENT,
    PLAYERID INTEGER NOT NULL,
    GAMEID INTEGER NOT NULL,
    FOREIGN KEY (PLAYERID) REFERENCES Player (PLAYERID),
    FOREIGN KEY (GAMEID) REFERENCES Game (GAMEID)
);

CREATE TABLE IF NOT EXISTS TableShot (
    TABLEID INTEGER NOT NULL,
    SHOTID INTEGER NOT NULL,
    PRIMARY KEY (TABLEID, SHOTID),
    FOREIGN KEY (TABLEID) REFERENCES TTable (TABLEID),
    FOREIGN KEY (SHOTID) REFERENCES Shot (SHOTID)
);

-- Whose turn it is, the groups, the winner and the resting balls, as JSON. KEY is the random id in
-- the game's link, so games cannot be found by counting GAMEIDs.
CREATE TABLE IF NOT EXISTS GameState (
    GAMEID INTEGER PRIMARY KEY,
    KEY TEXT NOT NULL UNIQUE,
    STATE TEXT NOT NULL,
    UPDATED TEXT NOT NULL DEFAULT (datetime('now')),
    FOREIGN KEY (GAMEID) REFERENCES Game (GAMEID)
);
